# Euphorbia icon: thin curved leaves rising from the crown, everything clipped to a
# circle centred on the leaf base. Usage: python3 -I mkicon.py <out.svg>
import math, sys

BASE = (512, 340)     # where the leaves start (top of the body)
R = 320               # circle radius around BASE, in drawing units
W = 8                # half-width of a leaf at its widest

def bez(p0, p1, p2, p3, t):
    u = 1 - t
    return tuple(u**3*a + 3*u*u*t*b + 3*u*t*t*c + t**3*d for a, b, c, d in zip(p0, p1, p2, p3))

def leaf(tip_dx, tip_dy, bend):
    """Leaf rising straight up from the base, then curving out to the tip."""
    bx, by = BASE
    p0 = (bx + tip_dx * 0.22, by + 14 + abs(tip_dx) * 0.08)
    p1 = (bx + tip_dx * 0.26, by - 80)          # leaves the base pointing up
    p2 = (bx + tip_dx * (0.25 - bend * 0.5), by + tip_dy - 60 - bend * 120)
    p3 = (bx + tip_dx, by + tip_dy)
    n = 40
    pts = [bez(p0, p1, p2, p3, i / n) for i in range(n + 1)]
    left, right = [], []
    for i, (x, y) in enumerate(pts):
        t = i / n
        a = pts[min(i + 1, n)]
        b = pts[max(i - 1, 0)]
        dx, dy = a[0] - b[0], a[1] - b[1]
        L = math.hypot(dx, dy) or 1
        nx, ny = -dy / L, dx / L
        w = W * math.sin(math.pi * min(1, t * 1.15)) ** 0.9 * (1 - 0.1 * t) + 0.8
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    poly = left + right[::-1]
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in poly) + ' Z'

