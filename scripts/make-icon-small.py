# Generates build/icon-small.svg, the round app icon:
#   a disc with a swirling orange / pink / purple / yellow background,
#   Euphorbia 'Sotetsukirin' (괴마옥) tilted 20° clockwise, its body running to
#   the edge of the disc, each diamond cell and each leaf with its own gradient.
# Usage: python3 -I scripts/make-icon-small.py build/icon-small.svg
#        then scripts/render-icons.sh
import math, sys

BASE = (512, 342)  # where the leaves start (top of the body), drawing units
BODY = 'M512 320 C615 320 676 420 698 560 C722 720 720 860 690 915 C660 955 600 955 512 955 C424 955 364 955 334 915 C304 860 302 720 326 560 C348 420 409 320 512 320 Z'

# Leaves: (angle from straight up in degrees, + = right; length; half-width;
# bend: how far the middle curves sideways, + = clockwise). Uneven on purpose.
LEAVES = [
    (-74, 190, 15, -18),
    (-47, 262, 17, -26),
    (-21, 214, 14, 14),
    (9, 286, 16, -20),
    (33, 228, 15, 22),
    (58, 268, 17, 30),
    (79, 172, 13, 16),
]


def leaf(angle, length, half, bend):
    a = math.radians(angle)
    ux, uy = math.sin(a), -math.cos(a)          # along the leaf
    nx, ny = -uy, ux                              # to its right
    bx, by = BASE[0] + ux * 6, BASE[1] + uy * 6
    tx, ty = bx + ux * length, by + uy * length
    mx, my = bx + ux * length * 0.45 + nx * bend, by + uy * length * 0.45 + ny * bend
    p = lambda x, y: f'{x:.1f} {y:.1f}'
    # Two curved sides from base to tip, widest a little below the middle.
    return (f'M{p(bx - nx * half * 0.5, by - ny * half * 0.5)} '
            f'C{p(mx - nx * half * 1.3, my - ny * half * 1.3)} {p(tx - ux * length * 0.25 - nx * half * 0.4, ty - uy * length * 0.25 - ny * half * 0.4)} {p(tx, ty)} '
            f'C{p(tx - ux * length * 0.25 + nx * half * 0.4, ty - uy * length * 0.25 + ny * half * 0.4)} {p(mx + nx * half * 1.3, my + ny * half * 1.3)} {p(bx + nx * half * 0.5, by + ny * half * 0.5)} Z')


def diamond(cx, cy):
    return f'M{cx} {cy - 26} L{cx + 38} {cy} L{cx} {cy + 26} L{cx - 38} {cy} Z'


def tip(cx, cy):
    return f'M{cx} {cy - 20} L{cx + 7} {cy - 9} L{cx} {cy - 4} L{cx - 7} {cy - 9} Z'


CELLS = [(46, 32), (0, 0), (92, 0), (0, 64), (92, 64)]
cells = '\n'.join(f'      <path d="{diamond(x, y)}" fill="url(#cell)"/>' for x, y in CELLS)
tips = ' '.join(tip(x, y) for x, y in CELLS)
leaves = '\n'.join(f'        <path d="{leaf(*l)}" fill="url(#leaf)"/>' for l in LEAVES)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Round app icon, generated by scripts/make-icon-small.py. -->
  <defs>
    <!-- Background: soft colour clouds swirled around the centre. -->
    <radialGradient id="bgBase" cx="0.5" cy="0.55" r="0.6">
      <stop offset="0" stop-color="#ffb347"/>
      <stop offset="1" stop-color="#ff7a2e"/>
    </radialGradient>
    <radialGradient id="purple" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#8b3fd9"/><stop offset="1" stop-color="#8b3fd9" stop-opacity="0"/></radialGradient>
    <radialGradient id="pink" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#ff4f8b"/><stop offset="1" stop-color="#ff4f8b" stop-opacity="0"/></radialGradient>
    <radialGradient id="yellow" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#ffe14d"/><stop offset="1" stop-color="#ffe14d" stop-opacity="0"/></radialGradient>
    <filter id="swirl" x="-20%" y="-20%" width="140%" height="140%">
      <feTurbulence type="fractalNoise" baseFrequency="0.005" numOctaves="2" seed="11" result="noise"/>
      <feDisplacementMap in="SourceGraphic" in2="noise" scale="230" xChannelSelector="R" yChannelSelector="G" result="moved"/>
      <feGaussianBlur in="moved" stdDeviation="30"/>
    </filter>
    <clipPath id="discClip"><circle cx="512" cy="512" r="470"/></clipPath>
    <!-- Each diamond cell: light at its top corner, dark at its bottom one. -->
    <linearGradient id="cell" x1="0.5" y1="0" x2="0.5" y2="1">
      <stop offset="0" stop-color="#7cbd6e"/>
      <stop offset="0.55" stop-color="#3f7a46"/>
      <stop offset="1" stop-color="#22452a"/>
    </linearGradient>
    <!-- Each leaf: the fill runs from its base (dark) to its tip (light). -->
    <linearGradient id="leaf" x1="0" y1="1" x2="0" y2="0">
      <stop offset="0" stop-color="#2c5a34"/>
      <stop offset="1" stop-color="#86c873"/>
    </linearGradient>
    <pattern id="tub" width="92" height="64" patternUnits="userSpaceOnUse" x="20" y="14">
      <rect width="92" height="64" fill="#2a4f31"/>
{cells}
      <path d="{tips}" fill="#ffd27a" opacity="0.85"/>
    </pattern>
    <clipPath id="disc"><circle cx="512" cy="340" r="320"/></clipPath>
    <clipPath id="body"><path d="{BODY}"/></clipPath>
  </defs>
  <g clip-path="url(#discClip)">
    <circle cx="512" cy="512" r="470" fill="url(#bgBase)"/>
    <g filter="url(#swirl)">
      <ellipse cx="820" cy="700" rx="300" ry="360" fill="url(#purple)" opacity="1"/>
      <ellipse cx="760" cy="230" rx="330" ry="230" fill="url(#pink)" opacity="0.95"/>
      <ellipse cx="260" cy="250" rx="270" ry="220" fill="url(#yellow)" opacity="0.95"/>
      <ellipse cx="560" cy="930" rx="300" ry="180" fill="url(#pink)" opacity="0.8"/>
      <ellipse cx="560" cy="470" rx="200" ry="170" fill="url(#yellow)" opacity="0.45"/>
    </g>
  </g>
  <g transform="rotate(20 512 512)">
    <g transform="translate(512 512) scale(1.4688) translate(-512 -340)">
      <g clip-path="url(#disc)">
        <rect x="250" y="300" width="524" height="700" fill="url(#tub)" clip-path="url(#body)"/>
{leaves}
      </g>
    </g>
  </g>
</svg>
'''
open(sys.argv[1], 'w').write(svg)
print('ok')
